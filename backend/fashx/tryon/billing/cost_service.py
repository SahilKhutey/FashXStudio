"""Cost estimation and financial attribution service for Virtual Try-On inference.

Maintains standard pricing schedules per provider and computes realized spend,
estimated cache savings, and cost efficiency metrics.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from datetime import datetime
from decimal import Decimal

from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

logger = logging.getLogger(__name__)

# Standard default unit pricing (USD per successful inference submission)
DEFAULT_PROVIDER_PRICING: dict[str, Decimal] = {
    "fashn": Decimal("0.0750"),
    "fashn/v1": Decimal("0.0750"),
    "fashn/v1.5": Decimal("0.0850"),
    "mock": Decimal("0.0000"),
}


@dataclass
class CostSummary:
    """Summary of financial metrics over a time interval."""

    total_spend_usd: Decimal
    total_operations: int
    successful_jobs: int
    cost_per_successful_job_usd: Decimal
    cache_hits: int
    estimated_cache_savings_usd: Decimal


class TryOnCostService:
    """Calculates inference costs, estimates savings, and monitors unit economics."""

    def __init__(
        self,
        session: AsyncSession,
        custom_pricing: dict[str, Decimal] | None = None,
    ) -> None:
        self.session = session
        self.pricing = custom_pricing or DEFAULT_PROVIDER_PRICING.copy()

    def get_unit_cost(self, provider: str, model: str | None = None) -> Decimal:
        """Resolve unit inference cost in USD for a given provider and model."""
        clean_provider = provider.lower().strip()
        if model:
            key = f"{clean_provider}/{model.lower().strip()}"
            if key in self.pricing:
                return self.pricing[key]
        return self.pricing.get(clean_provider, Decimal("0.0750"))

    def estimate_submission_cost(
        self,
        provider: str,
        model: str | None = None,
        units: Decimal = Decimal("1.0"),
    ) -> Decimal:
        """Estimate cost before dispatching an inference submission."""
        unit_cost = self.get_unit_cost(provider, model)
        return (unit_cost * units).quantize(Decimal("0.0001"))

    def estimate_cache_savings(
        self,
        hit_count: int,
        provider: str = "fashn",
        model: str | None = None,
    ) -> Decimal:
        """Calculate the estimated financial savings generated by cache hits."""
        unit_cost = self.get_unit_cost(provider, model)
        return (Decimal(hit_count) * unit_cost).quantize(Decimal("0.0001"))

    async def get_period_cost_summary(
        self,
        from_time: datetime,
        to_time: datetime,
    ) -> CostSummary:
        """Aggregate total spend, successful jobs, and cache savings for a time window."""
        from database.models.tryon import TryOnJob, TryOnProviderUsage, TryOnResultCache

        # 1. Total spend from provider usage ledger
        usage_stmt = select(
            func.coalesce(func.sum(TryOnProviderUsage.total_cost_usd), 0),
            func.count(TryOnProviderUsage.id),
        ).where(
            TryOnProviderUsage.created_at >= from_time,
            TryOnProviderUsage.created_at <= to_time,
        )
        usage_res = await self.session.execute(usage_stmt)
        total_spend_raw, total_ops = usage_res.one()
        total_spend = Decimal(str(total_spend_raw)).quantize(Decimal("0.0001"))

        # 2. Total successful jobs
        jobs_stmt = select(func.count(TryOnJob.id)).where(
            TryOnJob.created_at >= from_time,
            TryOnJob.created_at <= to_time,
            TryOnJob.status == "COMPLETED",
        )
        jobs_res = await self.session.execute(jobs_stmt)
        successful_jobs = jobs_res.scalar_one()

        cost_per_job = Decimal("0.0000")
        if successful_jobs > 0:
            cost_per_job = (total_spend / Decimal(successful_jobs)).quantize(Decimal("0.0001"))

        # 3. Cache hits during period
        cache_stmt = select(func.coalesce(func.sum(TryOnResultCache.hit_count), 0)).where(
            TryOnResultCache.last_hit_at >= from_time,
            TryOnResultCache.last_hit_at <= to_time,
        )
        cache_res = await self.session.execute(cache_stmt)
        cache_hits = cache_res.scalar_one()

        savings = self.estimate_cache_savings(cache_hits)

        return CostSummary(
            total_spend_usd=total_spend,
            total_operations=total_ops,
            successful_jobs=successful_jobs,
            cost_per_successful_job_usd=cost_per_job,
            cache_hits=cache_hits,
            estimated_cache_savings_usd=savings,
        )
